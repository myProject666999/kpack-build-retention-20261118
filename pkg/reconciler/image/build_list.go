package image

import (
	"sort"
	"strconv"
	"strings"

	buildapi "github.com/pivotal/kpack/pkg/apis/build/v1alpha2"
)

const buildNameInfix = "-build-"

// buildList is a snapshot of the Builds owned by a single Image. Builds are
// kept in a stable oldest-first order (see buildOrderLess) and partitioned
// into the categories retention cares about.
type buildList struct {
	all []*buildapi.Build

	successful []*buildapi.Build
	failed     []*buildapi.Build
	running    []*buildapi.Build

	lastBuild *buildapi.Build
}

func newBuildList(builds []*buildapi.Build) buildList {
	sort.Slice(builds, func(i, j int) bool {
		return buildOrderLess(builds[i], builds[j])
	})

	list := buildList{all: builds}
	for _, build := range builds {
		switch {
		case build.IsRunning():
			// A Build with no Succeeded condition does not exist yet as far as
			// kpack is concerned. Treat it as running so it is never pruned.
			list.running = append(list.running, build)
		case build.IsSuccess():
			list.successful = append(list.successful, build)
		case build.IsFailure():
			list.failed = append(list.failed, build)
		}
	}

	if len(builds) > 0 {
		list.lastBuild = builds[len(builds)-1]
	}

	return list
}

// buildOrderLess defines a total order over the Builds of an Image, oldest
// first.
//
// The primary key is the build number. Build numbers are assigned by the Image
// controller and are monotonically increasing for the lifetime of the Image, so
// they express creation order without depending on wall-clock time. Creation
// timestamps alone are not a stable ordering: two Builds can be created within
// the same second, the cluster clock can move backwards, and the order objects
// are listed in is not guaranteed across informer restarts.
//
// The number is read from the image.kpack.io/buildNumber label, falling back to
// the "-build-<n>" suffix of the name generated by Image.Build. Only when neither
// is available do we use the creation timestamp, and name and UID are used as
// final tie-breakers. Every component is a stable property of the object, so
// the ordering does not change between reconciles or controller restarts.
//
// Builds whose number cannot be determined sort before every numbered Build.
// They are the oldest objects we know how to place, they are ordered
// deterministically among themselves, and placing them first guarantees such a
// Build can never be mistaken for the most recent Build (which drives build
// scheduling decisions).
func buildOrderLess(a, b *buildapi.Build) bool {
	aNumber, aNumbered := buildNumber(a)
	bNumber, bNumbered := buildNumber(b)

	if aNumbered != bNumbered {
		return !aNumbered
	}

	if aNumbered && aNumber != bNumber {
		return aNumber < bNumber
	}

	if !a.CreationTimestamp.Equal(&b.CreationTimestamp) {
		return a.CreationTimestamp.Before(&b.CreationTimestamp)
	}

	if a.Name != b.Name {
		return a.Name < b.Name
	}

	return a.UID < b.UID
}

func buildNumber(build *buildapi.Build) (int64, bool) {
	if raw, ok := build.Labels[buildapi.BuildNumberLabel]; ok {
		if number, err := strconv.ParseInt(raw, 10, 64); err == nil {
			return number, true
		}
	}

	// Fall back to the generated name. The v1alpha2 name is "<image>-build-<n>";
	// the legacy v1alpha1 name is "<image>-build-<n>-", so only accept the
	// leading digits after the infix and require them to be non-empty.
	if i := strings.LastIndex(build.Name, buildNameInfix); i >= 0 {
		digits := build.Name[i+len(buildNameInfix):]
		end := 0
		for end < len(digits) && digits[end] >= '0' && digits[end] <= '9' {
			end++
		}
		if end == 0 {
			return 0, false
		}
		if rest := digits[end:]; rest != "" && rest != "-" {
			return 0, false
		}
		if number, err := strconv.ParseInt(digits[:end], 10, 64); err == nil {
			return number, true
		}
	}

	return 0, false
}
